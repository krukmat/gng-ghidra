#!/usr/bin/env python3
"""Prepare R3's private fixed-view 64-KiB gngb CPU ROM from verified local ZIP.

Uses the original ROM reader (CRC + reset-vector checks) in src/poc.py.
Does NOT rerun Ghidra, launch MAME, download ROMs or create synthetic ROM.
A stale preexisting image is rejected, not silently overwritten.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from poc import read_rom  # noqa: E402

SCHEMA = "gng.r3.rom-preflight.v1"


def inside_out(path: Path) -> bool:
    return path.resolve().is_relative_to((ROOT / "out").resolve())


def prepare(source: Path, dest: Path) -> dict:
    if not inside_out(dest):
        raise ValueError("R3 generated flat ROM must remain inside ignored out/")
    if not source.is_file():
        raise ValueError("Local gngb ROM ZIP missing; expected roms/gng.zip")
    flat, mapping = read_rom(source)
    if len(flat) != 65536 or flat[0xfffe:0x10000] != b"\x60\x00":
        raise ValueError("R3 source is not a verified 64 KiB gngb fixed ROM view")
    actual = hashlib.sha256(flat).hexdigest()
    result = {
        "schema": SCHEMA,
        "status": "READY",
        "cpu": "MC6809",
        "driver": mapping["set"],
        "reset_vector": mapping["reset_vector"],
        "flat_rom_sha256": actual,
        "rom_image_bytes": len(flat),
        "bank_window": "bank4 snapshot in 0x4000..0x5fff; no dynamic bank switching",
        "created": False,
        "runtime_equivalence_verified": False,
    }
    if dest.exists():
        if not dest.is_file() or dest.read_bytes() != flat:
            raise ValueError(
                "Existing private R3 flat ROM differs from validated ZIP; "
                "refusing to overwrite. Inspect or back it up manually."
            )
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        # An in-memory validated image is the only source of generated bytes.
        # Exclusive file creation means a concurrent process cannot be overwritten.
        with dest.open("xb") as stream:
            stream.write(flat)
        result["created"] = True
    return result


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--rom", type=Path, default=ROOT / "roms/gng.zip")
    ap.add_argument("--out", type=Path, default=ROOT / "out/gngb-flat.bin")
    args = ap.parse_args()
    try:
        report = prepare(args.rom, args.out)
    except (ValueError, OSError, KeyError) as exc:
        ap.error(str(exc))
    # SHA hashes and status only; no CPU bytes or ROM payload leave the Mac.
    print("GNG_R3_ROM_PREFLIGHT=READY file=" + str(args.out))
    print("GNG_R3_ROM_IMAGE_CREATED=" + str(report["created"]).lower())
    print("GNG_R3_ROM_SHA256=" + report["flat_rom_sha256"])
    print("GNG_R3_ROM_EQUIVALENCE=NOT_TESTED")


if __name__ == "__main__":
    main()
