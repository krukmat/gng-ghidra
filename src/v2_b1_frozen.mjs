/** V2.B1: private frozen AOT package, no MAME/oracle dependency at runtime. */
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync,mkdirSync,lstatSync,existsSync} from 'node:fs';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {rendererUnknownCount} from './v2_b1_observable.mjs';

export const FORMAT='gng.v2.b1.frozen-aot.v1';
export const MODULES=['mc6809_aot_lib.mjs','gngb_runtime.mjs','gngb_block_key.mjs'];
export const ASSETS=['program.mjs','code.bin','overlays.bin',...MODULES];
export const sha256=data=>createHash('sha256').update(data).digest('hex');
const deny=code=>{throw Error('V2_B1_'+code);};
const isUintArray=a=>a instanceof Uint8Array || Buffer.isBuffer(a);
const isHash=h=>typeof h==='string'&&/^[0-9a-f]{64}$/.test(h);

export function rewriteProgram(source){
  if(typeof source!=='string'||!source.startsWith('// GENERATED by src/mc6809_aot.mjs from private ROM bytes. Do not commit.\n'))
    deny('GENERATED_SOURCE_REQUIRED');
  const anchor=/^import \* as L from "file:\/\/[^"\r\n]+";$/gm;
  const matches=[...source.matchAll(anchor)];
  if(matches.length!==1)deny('GENERATED_LIBRARY_IMPORT_UNEXPECTED');
  const out=source.replace(anchor,'import * as L from "./mc6809_aot_lib.mjs";');
  if(!out.includes('export const blocks=new Map();'))deny('BLOCK_MAP_MISSING');
  if(/(?:import\s*\(|\beval\s*\(|\bFunction\s*\()/.test(out))deny('DYNAMIC_RUNTIME_FORBIDDEN');
  return out;
}

/** Only build pipeline may call this with authenticated private ROM bytes. */
export function freezeBundle(dir,{generated,code,overlays=[],modules,provenance={}}){
  if(existsSync(dir))deny('DESTINATION_EXISTS');
  if(!isUintArray(code?.fixed)||code.fixed.length!==0x10000||
     !isUintArray(code?.banks)||code.banks.length!==0xa000)deny('CODE_IMAGE_INVALID');
  if(!Array.isArray(overlays)||!modules||MODULES.some(n=>typeof modules[n]!=='string'))
    deny('MODULES_OR_OVERLAYS_MISSING');
  const program=rewriteProgram(generated);
  if(modules['gngb_runtime.mjs'].includes("from './mc6809_aot.mjs'")||
     modules['gngb_block_key.mjs'].includes('import '))deny('RUNTIME_IMPORTS_COMPILER');
  const descriptors=[];
  const parts=[];
  let offset=0;
  for(const ov of overlays){
    if(!Number.isInteger(ov.start)||ov.start<0||ov.start>=0x3000||
       !isUintArray(ov.bytes)||ov.bytes.length<1||ov.start+ov.bytes.length>0x3000)
      deny('OVERLAY_INVALID');
    descriptors.push({start:ov.start,length:ov.bytes.length,offset});
    parts.push(Buffer.from(ov.bytes));offset+=ov.bytes.length;
  }
  if(!Number.isInteger(provenance?.frames)||provenance.frames<1||provenance.frames>20000 ||
     !Number.isInteger(provenance?.blocks)||provenance.blocks<1)
    deny('PROVENANCE_MISSING');
  const assets={
    'program.mjs':Buffer.from(program,'utf8'),
    'code.bin':Buffer.concat([Buffer.from(code.fixed),Buffer.from(code.banks)]),
    'overlays.bin':Buffer.concat(parts),
  };
  for(const name of MODULES)assets[name]=Buffer.from(modules[name],'utf8');
  mkdirSync(dir,{recursive:false,mode:0o700});
  const hashes={};
  for(const name of ASSETS){
    hashes[name]=sha256(assets[name]);
    writeFileSync(join(dir,name),assets[name],{flag:'wx',mode:0o600});
  }
  const manifest={
    schema:FORMAT,frames:provenance.frames,blocks:provenance.blocks,
    source_report_sha256:provenance.source_report_sha256??null,
    overlays:descriptors,files:hashes
  };
  writeFileSync(join(dir,'manifest.json'),JSON.stringify(manifest,null,2)+'\n',
                {flag:'wx',mode:0o600});
  return manifest;
}

/** Read only immutable local artifacts; no ZIP/ROM decoding or compilation. */
export function loadFrozen(dir){
  const mf=join(dir,'manifest.json');
  const st=lstatSync(mf);
  if(!st.isFile()||st.isSymbolicLink())deny('MANIFEST_SYMLINK_OR_NONFILE');
  const manifest=JSON.parse(readFileSync(mf,'utf8'));
  if(manifest.schema!==FORMAT||!Number.isInteger(manifest.frames)||
     manifest.frames<1||manifest.frames>20000||
     !Number.isInteger(manifest.blocks)||manifest.blocks<1||
     !Array.isArray(manifest.overlays)||!manifest.files||
     Object.keys(manifest.files).sort().join()!==[...ASSETS].sort().join())
    deny('MANIFEST_INVALID');
  const read=(name)=>{
    const f=join(dir,name);
    const stat=lstatSync(f);
    if(!stat.isFile()||stat.isSymbolicLink())deny('ASSET_SYMLINK_OR_NONFILE');
    const value=readFileSync(f);
    if(!isHash(manifest.files[name])||sha256(value)!==manifest.files[name])
      deny('ASSET_HASH_MISMATCH');
    return value;
  };
  const values=Object.fromEntries(ASSETS.map(name=>[name,read(name)]));
  const bytes=values['code.bin'],blob=values['overlays.bin'];
  if(bytes.length!==0x1a000)deny('CODE_IMAGE_LENGTH');
  const ramOverlays=[];
  let cursor=0;
  for(const ov of manifest.overlays){
    if(!Number.isInteger(ov.start)||ov.start<0||ov.start>=0x3000||
       !Number.isInteger(ov.length)||ov.length<1||ov.start+ov.length>0x3000||
       ov.offset!==cursor||cursor+ov.length>blob.length)deny('OVERLAY_MANIFEST_INVALID');
    ramOverlays.push({start:ov.start,bytes:Uint8Array.from(
      blob.subarray(cursor,cursor+ov.length))});
    cursor+=ov.length;
  }
  if(cursor!==blob.length)deny('OVERLAY_TRAILING_BYTES');
  const code={fixed:Uint8Array.from(bytes.subarray(0,0x10000)),
    banks:Uint8Array.from(bytes.subarray(0x10000)),ramOverlays};
  return {manifest,code};
}

export async function runFrozen(dir,{frames,onFrame}={}){
  const {manifest,code}=loadFrozen(dir);
  const n=frames??manifest.frames;
  if(!Number.isInteger(n)||n<1||n>manifest.frames)deny('FRAME_REQUEST_INVALID');
  // Dynamic imports load the frozen ESM modules. No codegen/imports from repo.
  const {blocks}=await import(pathToFileURL(join(dir,'program.mjs')).href);
  const {createBoard}=await import(pathToFileURL(join(dir,'gngb_runtime.mjs')).href);
  if(!(blocks instanceof Map)||blocks.size!==manifest.blocks)deny('BLOCK_COUNT_MISMATCH');
  const hashes=[],unknowns=[],visibleUnknowns=[];
  const board=createBoard(code,blocks,{frames:n,onFrame:r=>{
    const h=createHash('sha256');
    h.update(r.record);h.update(r.known);
    h.update(JSON.stringify([r.scroll,r.bank,r.latch,r.sprite_buffer_valid,r.writes]));
    hashes.push(h.digest('hex'));
    unknowns.push(r.known.reduce((count,k)=>count+(k!==255),0));
    visibleUnknowns.push(rendererUnknownCount(r));
    if(onFrame)onFrame(r);
  }});
  const result=board.run();
  if(result.status!=='FRAMES_DONE'||hashes.length!==n)
    deny('INCOMPLETE_OR_UNCOMPILED_'+result.status);
  return {schema:'gng.v2.b1.frozen-run.v1',status:'FRAMES_DONE',
    frames:n,unknowns,visible_unknowns:visibleUnknowns,frame_hashes:hashes,
    sequence_sha256:sha256(hashes.join('\n')+'\n'),
    first_fully_known:unknowns.findIndex(x=>x===0)+1||null,
    first_renderer_known:visibleUnknowns.findIndex(x=>x===0)+1||null,
    events:board.state.events,
    blocks:blocks.size};
}
