import test from 'node:test';
import assert from 'node:assert/strict';
import {createGngbBoardMemory} from '../src/gngb_board_memory.mjs';
import {renderGngbBoardFrame} from '../src/gngb_frame_pipeline.mjs';

const cpu={PC:0x6000,A:0,B:0,X:0,Y:0,U:0,S:0x4000,DP:0,CC:0};
function setup(){
  const b=createGngbBoardMemory();
  for(let a=0x2000;a<=0x2fff;a++)b.write8(a,0);
  for(let a=0x1e00;a<=0x1fff;a++)b.write8(a,0xf8);
  b.write8(0x3c00,0);
  for(let i=0;i<256;i++){b.write8(0x3800+i,0);b.write8(0x3900+i,0);}
  for(let a=0x3b08;a<=0x3b0b;a++)b.write8(a,0);
  return b;
}
function assets(){
  const chars=new Uint8Array(0x4000),tiles=new Uint8Array(0x18000),
    sprites=new Uint8Array(0x20000);
  chars.fill(255);sprites.fill(255);
  const gfx={chars,tiles,sprites};
  return gfx;
}
function pixel(frame,x,y){return [...frame.rgba.slice((y*256+x)*4,(y*256+x)*4+4)];}
test('R4.2.C3 default pipeline consumes board scroll and RGBx palette, not manual arguments',()=>{
  const b=setup(),gfx=assets();
  b.write8(0x3800,0xf0);b.write8(0x3900,0); // red 255
  const first=renderGngbBoardFrame({board:b,...gfx});
  assert.equal(first.scroll_and_palette_board_derived,true);
  assert.equal(first.video_state_source,'BOARD_MMIO');
  assert.deepEqual(pixel(first,0,0),[255,0,0,255]);
  b.write8(0x3800,0x0f); // green 255
  assert.deepEqual(pixel(renderGngbBoardFrame({board:b,...gfx}),0,0),[0,255,0,255]);
});
test('R4.2.C4 scroll updates alter visible tile raster using board register writes',()=>{
  const b=setup(),gfx=assets();
  // BG tile #1 pen0 -> index1; tile0 and tile1 bitplanes differ.
  b.write8(0x2800+33,1); // col1/row1; visible y=0 corresponds to hardware y=16
  // BG graphic #1 at x=0,y=0 set pen 7 via planar bits.
  // Existing decoder samples index * 256 (bits), which is byte offset 32.
  gfx.tiles[32]=0xff;gfx.tiles[0x8000+32]=0xff;gfx.tiles[0x10000+32]=0xff;
  b.write8(0x3800,0xf0); // color index0 red
  b.write8(0x3807,0x0f); // index7 green
  const before=renderGngbBoardFrame({board:b,...gfx});
  b.write8(0x3b08,16); // scroll x moves col1 into first column
  const after=renderGngbBoardFrame({board:b,...gfx});
  assert.notDeepEqual(before.rgba,after.rgba);
  assert.equal(after.scroll_and_palette_board_derived,true);
});
test('R4.2.C4 0x3c00 DMA remains independent and read B4 policy intact',()=>{
  const b=createGngbBoardMemory({readUnmapped3c00:()=>0xa1});
  assert.equal(b.read8(0x3c00),0xa1);
  assert.throws(()=>b.write8(0x3c00,0),/SOURCE_INCOMPLETE/);
  b.write8(0x3b08,3);
  assert.equal(b.stats().scroll_register_bytes_written,1);
  assert.throws(()=>b.read8(0x3b08),/UNMODELED_IO_OR_ROM_READ/);
  assert.throws(()=>b.read8(0x3800),/UNMODELED_IO_OR_ROM_READ/);
  assert.throws(()=>b.write8(0x3a00,0),/UNMODELED_IO_OR_ROM_WRITE/);
  assert.equal(b.stats().sprite_dma_transfers,0);
});
test('R4.2.C4 generated byte stores to scroll/palette commit atomically',()=>{
  const b=setup();
  const step=(r,_word,writeByte)=>{
    writeByte(0x3b08,33);
    writeByte(0x3b09,2);
    return {...r,PC:r.PC+1};
  };
  b.stepStatic(step,cpu,{commit:false});
  assert.equal(b.snapshotVideoRegisters().scroll.x,0);
  const result=b.stepStatic(step,cpu);
  assert.equal(result.writes_by_region.SCROLL_MMIO,2);
  assert.equal(b.snapshotVideoRegisters().scroll.x,545);
  assert.throws(()=>b.stepStatic((r,_word,w)=>{
    w(0x3900,0xff); return {...r,PC:65536};
  },cpu),/INVALID_MC6809_REGISTER_STATE/);
  assert.equal(b.snapshotVideoRegisters().palette[2],0);
  assert.throws(()=>b.stepStatic((r,_word,w)=>{
    w(0x3b08,1);w(0x2000,3);return {...r,PC:r.PC+1};
  },cpu),/R42_MIXED_MMIO_AND_RAM_EFFECTS_UNSUPPORTED/);
  assert.equal(b.snapshotVideoRegisters().scroll.x,545);
});
test('R4.2.C4 output blocked on incomplete board state or half external overrides',()=>{
  const b=createGngbBoardMemory(),gfx=assets();
  for(let a=0x2000;a<=0x2fff;a++)b.write8(a,0);
  for(let a=0x1e00;a<=0x1fff;a++)b.write8(a,0xf8);
  b.write8(0x3c00,0);
  assert.throws(()=>renderGngbBoardFrame({board:b,...gfx}),/R42_VIDEO_REGISTERS_UNINITIALIZED/);
  assert.throws(()=>renderGngbBoardFrame({board:b,...gfx,palette:new Uint8Array(1024)}),
    /R42_INCOMPLETE_EXTERNAL_VIDEO_STATE/);
});
test('R4.2.C5 source state snapshots and reset behavior are explicit',()=>{
  const b=setup(),gfx=assets(),first=renderGngbBoardFrame({board:b,...gfx});
  assert.equal(first.original_game_logic_running,false);
  assert.equal(first.native_pixel_equivalence_verified,false);
  assert.equal(first.autonomous_cpu_frame_rendered,false);
  assert.equal(b.stats().palette_base_bytes_written,256);
  assert.equal(b.stats().palette_ext_bytes_written,256);
  b.clearLabState();
  assert.throws(()=>b.snapshotVideoRegisters(),/UNINITIALIZED/);
});
